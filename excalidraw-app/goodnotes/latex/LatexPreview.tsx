/**
 * The rendered side of the LaTeX editor.
 *
 * Renders the parsed document as React elements, not as an HTML string.
 * That is deliberate: a `.tex` file is user input, and building HTML from
 * it to hand to `dangerouslySetInnerHTML` would make every document an
 * injection vector into the app that stores every other document. The one
 * exception is the maths, which arrives as SVG from MathJax — see the
 * note on `MathBlock`.
 *
 * Laid out as A4 pages so the preview is what printing produces, rather
 * than a web page that happens to be near it.
 */

import React, { useEffect, useMemo, useRef, useState } from "react";

import { MathRenderError, renderMathToSvg } from "../math/renderMath";
import { createMathSpec } from "../math/spec";

import "./LatexPreview.scss";

import type { Block, Inline, LatexDocument } from "./parse";

/**
 * One piece of typeset maths.
 *
 * MathJax's SVG output is inserted with `dangerouslySetInnerHTML`, and
 * that is safe *here* for a specific reason: the string is generated by
 * MathJax from the TeX, not copied from it. MathJax does not emit script
 * elements or event handlers, and the TeX never reaches the DOM as
 * markup. Rendering it as text instead would show the SVG source.
 */
const MathPiece: React.FC<{ tex: string; display: boolean }> = ({
  tex,
  display,
}) => {
  const [svg, setSvg] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let cancelled = false;
    setError(null);
    // Size the typesetting to the body text rather than scaling the SVG
    // afterwards with CSS. Forcing `height: 1.05em` looked right for a
    // formula with superscripts and wrong for a lone glyph: a bare alpha
    // has no ascenders, so pinning its total height to the line made the
    // letter itself line-height tall. Letting MathJax lay out at the
    // body size gets both cases right.
    renderMathToSvg(
      createMathSpec(tex, { display, fontSize: display ? 22 : 16 }),
    )
      .then((result) => {
        if (!cancelled) {
          setSvg(result.svg);
        }
      })
      .catch((caught) => {
        if (!cancelled) {
          setError(
            caught instanceof MathRenderError
              ? caught.message
              : "This formula could not be typeset.",
          );
        }
      });
    return () => {
      cancelled = true;
    };
  }, [tex, display]);

  if (error) {
    return (
      <span className="gn-tex__matherror" title={error}>
        {tex}
      </span>
    );
  }
  if (!svg) {
    // the source, so the line does not jump when the SVG arrives
    return <span className="gn-tex__mathpending">{tex}</span>;
  }
  return (
    <span
      className={display ? "gn-tex__mathblock" : "gn-tex__mathinline"}
      // eslint-disable-next-line react/no-danger
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
};

const renderInline = (nodes: Inline[], keyPrefix = ""): React.ReactNode[] =>
  nodes.map((node, index) => {
    const key = `${keyPrefix}-${index}`;
    switch (node.kind) {
      case "text":
        return <React.Fragment key={key}>{node.text}</React.Fragment>;
      case "break":
        return <br key={key} />;
      case "math":
        return <MathPiece key={key} tex={node.tex} display={false} />;
      case "ref":
        return (
          <span key={key} className="gn-tex__ref">
            {node.label}
          </span>
        );
      case "emph": {
        const children = renderInline(node.children, key);
        if (node.style === "bold") {
          return <strong key={key}>{children}</strong>;
        }
        if (node.style === "italic") {
          return <em key={key}>{children}</em>;
        }
        if (node.style === "mono") {
          return <code key={key}>{children}</code>;
        }
        return (
          <span key={key} className="gn-tex__underline">
            {children}
          </span>
        );
      }
      default:
        return null;
    }
  });

const renderBlock = (block: Block, key: string): React.ReactNode => {
  switch (block.kind) {
    case "title":
      return (
        <header className="gn-tex__title" key={key}>
          <h1>{renderInline(block.title, `${key}t`)}</h1>
          {block.author.length > 0 && (
            <p className="gn-tex__author">
              {renderInline(block.author, `${key}a`)}
            </p>
          )}
          {block.date.length > 0 && (
            <p className="gn-tex__date">
              {renderInline(block.date, `${key}d`)}
            </p>
          )}
        </header>
      );
    case "heading": {
      const content = (
        <>
          {block.number && (
            <span className="gn-tex__secnum">{block.number}</span>
          )}
          {renderInline(block.children, key)}
        </>
      );
      if (block.level === 1) {
        return <h2 key={key}>{content}</h2>;
      }
      if (block.level === 2) {
        return <h3 key={key}>{content}</h3>;
      }
      return <h4 key={key}>{content}</h4>;
    }
    case "paragraph":
      return <p key={key}>{renderInline(block.children, key)}</p>;
    case "list": {
      const items = block.items.map((item, i) => (
        <li key={`${key}i${i}`}>
          {item.map((child, j) => renderBlock(child, `${key}i${i}b${j}`))}
        </li>
      ));
      return block.ordered ? (
        <ol key={key}>{items}</ol>
      ) : (
        <ul key={key}>{items}</ul>
      );
    }
    case "math":
      return (
        <div className="gn-tex__display" key={key}>
          <MathPiece tex={block.tex} display />
          {block.number && (
            <span className="gn-tex__eqnum">({block.number})</span>
          )}
        </div>
      );
    case "verbatim":
      return (
        <pre className="gn-tex__verbatim" key={key}>
          {block.text}
        </pre>
      );
    default:
      return null;
  }
};

export interface LatexPreviewProps {
  document: LatexDocument | null;
  /** Shown in the footer so nobody mistakes this for pdfTeX output. */
  engineLabel: string;
}

export const LatexPreview = React.forwardRef<HTMLDivElement, LatexPreviewProps>(
  ({ document: parsed, engineLabel }, ref) => {
    const rendered = useMemo(
      () => parsed?.blocks.map((block, i) => renderBlock(block, `b${i}`)),
      [parsed],
    );
    const sheetRef = useRef<HTMLDivElement | null>(null);

    if (!parsed) {
      return (
        <div className="gn-tex__preview" ref={ref}>
          <p className="gn-tex__note">Nothing to preview yet.</p>
        </div>
      );
    }

    return (
      <div className="gn-tex__preview" ref={ref}>
        {parsed.warnings.length > 0 && (
          <ul className="gn-tex__warnings" role="status">
            {parsed.warnings.map((warning) => (
              <li key={warning}>{warning}</li>
            ))}
          </ul>
        )}

        <article className="gn-tex__sheet" ref={sheetRef}>
          {rendered}
        </article>

        {parsed.unsupported.length > 0 && (
          <p className="gn-tex__note">
            Shown as plain text, because {engineLabel} does not implement{" "}
            {parsed.unsupported.join(", ")}.
          </p>
        )}
      </div>
    );
  },
);

LatexPreview.displayName = "LatexPreview";
